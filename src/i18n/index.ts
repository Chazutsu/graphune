const catalogs: Record<Locale, Record<MessageKey, string>> = { en, ja };
let activeLocale: Locale = "en";
const listeners = new Set<() => void>();

export function resolveLocale(preference: LanguagePreference, systemLocale?: string): Locale {
	if (preference === "en" || preference === "ja") return preference;
	const locale = systemLocale ?? (typeof navigator === "undefined" ? "en" : navigator.language);
	return locale.toLowerCase().startsWith("ja") ? "ja" : "en";
}

export function setLocale(preference: LanguagePreference, systemLocale?: string): Locale {
	const nextLocale = resolveLocale(preference, systemLocale);
	if (nextLocale === activeLocale) return activeLocale;
	activeLocale = nextLocale;
	for (const listener of listeners) listener();
	return activeLocale;
}

export function subscribeLocaleChange(listener: () => void): () => void {
	listeners.add(listener);
	return () => listeners.delete(listener);
}

export function getLocale(): Locale {
	return activeLocale;
}

export function getCatalog(locale: Locale): Readonly<Record<MessageKey, string>> {
	return catalogs[locale];
}

export function t(key: MessageKey, variables?: Record<string, string | number>): string {
	const message = catalogs[activeLocale][key] ?? en[key];
	if (!variables) return message;
	return message.replace(/\{(\w+)\}/g, (_, name: string) => String(variables[name] ?? `{${name}}`));
}
